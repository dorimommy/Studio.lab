  function applyLanguage(lang, ctx) {
    if (!lang || !LANG_CODES_SET.has(lang)) return;
    currentLang = lang;
    try {
      localStorage.setItem(LANG_STORAGE_KEY, lang);
    } catch (_) {}
    if (ctx && typeof ctx.setState === 'function' && ctx.state.language !== lang) {
      ctx.setState({ language: lang }, { save: true });
    }
    window.dispatchEvent(new CustomEvent('__sl_languageChanged', { detail: { language: lang } }));
  }

  function isWelcomeCompleted(ctx) {
    try {
      if (localStorage.getItem(WELCOME_STORAGE_KEY) === 'true') return true;
    } catch (_) {}
    if (ctx && ctx.state && ctx.state.welcomeCompleted === true) return true;
    return false;
  }

  function markWelcomeCompleted(lang, ctx) {
    try {
      localStorage.setItem(WELCOME_STORAGE_KEY, 'true');
      localStorage.setItem(LANG_STORAGE_KEY, lang);
    } catch (_) {}
    if (ctx && typeof ctx.setState === 'function') {
      ctx.setState({ welcomeCompleted: true, language: lang }, { save: true });
    }
  }

