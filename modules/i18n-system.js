  function t(keyOrText, secondArg) {
    if (keyOrText == null || keyOrText === '') return '';
    const raw = String(keyOrText);

    // Guard: if secondArg is a language code (e.g. 'en', 'vi'), treat it as language override,
    // NEVER as fallback display text!
    const isSecondArgLangCode = typeof secondArg === 'string' && LANG_CODES_SET.has(secondArg);
    const lang = isSecondArgLangCode ? secondArg : getLang();
    const fallback = isSecondArgLangCode ? undefined : secondArg;

    const lookupKey = Object.prototype.hasOwnProperty.call(UI_TRANSLATIONS.en, raw)
      ? raw
      : (EN_TEXT_TO_KEY[raw.trim()] || raw);

    const baseDict = UI_TRANSLATIONS[lang] || UI_TRANSLATIONS.en;
    const extraDict = EXTRA_LANG_OVERRIDES[lang] || {};

    if (Object.prototype.hasOwnProperty.call(extraDict, lookupKey)) return extraDict[lookupKey];
    if (Object.prototype.hasOwnProperty.call(baseDict, lookupKey)) return baseDict[lookupKey];
    if (Object.prototype.hasOwnProperty.call(UI_TRANSLATIONS.en, lookupKey)) return UI_TRANSLATIONS.en[lookupKey];

    return fallback !== undefined ? fallback : raw;
  }

